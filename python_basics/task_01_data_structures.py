# Task 1: Python data structures

# A list can store duplicate values.
name = ["aman", "rahul", "riya", "riya", "priya"]

# Convert the list into a set to keep only unique names.
set_name = set(name)

print("\nList of students:", name)
print("\nSet of students:", set_name)

# A dictionary stores student names as keys and marks as values.
dic = {"riya": 30, "priya": 34, "rahul": 45}
print("\nDictionary of students:", dic)
